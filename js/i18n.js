const LANG_KEY = "nvk-lang";

function normalizeLang(value) {
  return value === "en" ? "en" : "ua";
}

function getInitialLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved) return normalizeLang(saved);
  const nav = (navigator.language || "").toLowerCase();
  return nav.startsWith("uk") || nav.startsWith("ru") ? "ua" : "en";
}

function applyTranslations(lang) {
  const dict = translations[lang] || translations.ua;
  document.documentElement.lang = lang === "ua" ? "uk" : "en";
  document.documentElement.dataset.lang = lang;
  document.title = dict["meta.title"];

  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", dict["meta.description"]);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = dict[key];
    if (value == null) return;
    el.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    const value = dict[key];
    if (value == null) return;
    el.setAttribute("placeholder", value);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    const value = dict[key];
    if (value == null) return;
    el.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-lang-code]").forEach((el) => {
    el.textContent = dict["lang.code"];
  });
}

function setLang(lang) {
  const next = normalizeLang(lang);
  localStorage.setItem(LANG_KEY, next);
  applyTranslations(next);
  return next;
}

function toggleLang(current) {
  return setLang(normalizeLang(current) === "ua" ? "en" : "ua");
}

window.NVK_I18N = {
  translations,
  LANG_KEY,
  normalizeLang,
  getInitialLang,
  applyTranslations,
  setLang,
  toggleLang,
};
